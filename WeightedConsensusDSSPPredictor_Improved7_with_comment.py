# 7. 予測関数
# ============================================
# ------------------------------------------------------------
# 【数値ラベル → 二次構造文字（H/E/C）への逆変換テーブル】
# ------------------------------------------------------------
# ■ この辞æ の役割
#   機械学習モデル（MLPClassifier）は、分類結果を
#       0, 1, 2
#   のような「整数ラベル」で出力する。
#
#   しかし、二次構造の最終的な表現は
#       'H'（Helix）
#       'E'（β-sheet）
#       'C'（Coil）
#   の **文字列** で扱いたい。
#
#   そこで、この辞書 inv を使って、
#       0 → 'H'
#       1 → 'E'
#       2 → 'C'
#   のように、数値ラベルを元の二次構造文字に戻す。
#
# -----------------------------------------------------
# ■ なぜ逆変換が必要なのか？
#   ・学習時：文字列（H/E/C）を数値（0/1/2）に変換してモデルに渡す
#   ・予測時：モデルは数値（0/1/2）を返す
#   ・出力時：人間が読むために再び文字列（H/E/C）に戻す必要がある
#
#   つまり、inv は「予測結果を人間が読める形式に戻す」ための辞書。
#
# ------------------------------------------------------------
# ■ 使用例
#  [0, 0, 1, 2, 2]
#   ''.join(inv[i] for i in pred)
#       → "HHECC"
#
#   このように、モデルの出力を二次構造列として復元できる。
#
# ------------------------------------------------------------
# ■ この辞書の構造
#   ・キー（0,1,2）は整数ラベル
#   ・値（'H','E','C'）は DSSP の coarse-grained 二次構造
#
#   inv[0] → 'H'
#   inv[1] → 'E'
#   inv[2] → 'C'
#
# ------------------------------------------------------------
inv = {0:'H', 1:'E', 2:'C'}

# ------------------------------------------------------------
# 【predict_ss】
# アミノ酸配列（一次構造）から二次構造（H/E/C）を予測するメイン関数
# ------------------------------------------------------------
# ■ 役割（この関数が何をするか）
#   入力されたアミノ酸配列 seq に対して、
#       1. スライディングウィンドウを作成（window 残基ずつ）
#       2. 各ウィンドウを one-hot ベースの特徴量に変換    
#       3. 学習済み MLP モデルで H/E/C を予測
#       4. 予測結果（数値ラベル）を H/E/C の文字列に変換
#       5. スムージング処理でノイズを除去し、生物学的に自然な形に補正
#
#   という一連の処理を行い、最終的な二次構造列を返す。
#
# ------------------------------------------------------------
# ■ 引数
#   seq : str
#       アミノ酸配列（例："ACDEFGHIKLMNPQRSTVWY"）
#      文字・小文字は問わないが、内部で upper() されることが多い。
#
#   window : int（デフォルト 15）
#       スライディングウィンドウの幅。
#       各残基の周囲の文脈（前後のアミノ酸）をどれだけ見るかを決める。
#
#       例：window=15 の場合
#           中心残基の前後 7 残基を含む 15 残基の局所配列を特徴量化する。
#
# ---------------------------------------------------  # ■ 出力
#   str（例："HHHEECCCHHHCCEE"）
#
#   ・長さは入力配列 seq と同じ
#   ・各文字は 'H', 'E', 'C' のいずれか
#   ・スムージング済みのため、孤立した H/E が減り、
#     生物学的に自然な二次構造列になっている
#
# ------------------------------------------------------------
# ■ この関数が必要な理由
#   ・MLP モデルは「固定長の特徴量ベクトル」を入力として受けため、
#     可変長のアミノ酸配列をそのまま渡すことはできない。
#
#   ・そこで、配列を window 幅でスライドさせて
#       → 各位置ごとに局所特徴量を作成
#       → MLP で分類
#       → H/E/C を並べて二次構造列を構築
#
#   という処理が必要になる。
#
# ------------------------------------------------------------
# ■ 関数内部の主な処理の流れ（概要）
#   1. make_windows(seq, window)
#         → 配列を window 幅で切り出したリストを作成
#
#   2. encode_window(w)
#         → 各ウィンドウを one-hot ベクトルに変換
#
#   3. clf.predict(X)
#         → MLP による H/E/C の生予測（0/1/2）
#
#   4. inv[label] で文字に変換
#         → 0→H, 1→E, 2→C
#
#   5. smooth_ss(ss)
#         → ノイズ除去・連続化（H/E の孤立点を補正）
#
#   6. 最終的な二次構造列を返す
#
# ------------------------------------------------------------
# ■ この関数は「予測の入口」であり、外部から呼び出す唯一の API
#   ・ファイル入力（predict_from_file）
#   ・GUI/CLI ツール
#   ・Web アプリ
#
#   など、どこからでもこの関数を呼べば二次構造予測ができるように設計されている。
# ------------------------------------------------------------
def predict_ss(seq, window=15):

    # ------------------------------------------------------------
    # 【1. 入力アミノ酸配列からスライディングウィンドウを作成】
    # ------------------------------------------------------------
    # 目的：
    #   MLP は「固定長ベクトル」しか入力できないため、
    #   可変長のアミノ酸配列 seq をそのまま渡すことはできない。
    #
    #   そこで、配列の各位置 i を中心に、
    #       window 残基（例ï®局所配列（コンテキスト）を切り出していく。
    #
    #   例：seq = "ACDEFG"
    #       window=3 の場合
    #       → ["ACD", "CDE", "DEF", "EFG"]
    #
    #   この「ウィンドウ列」が MLP の入力の元になる。
    # ------------------------------------------------------------
    windows = make_windows(seq, window)


    # ------------------------------------------------------------
    # 【2. 各ウィンドウを one-hot ベクトルに変換】
    # ------------------------------------------------------------
    # 目的：
    #   MLP に入力するためには、文字列（アミノ酸）を
    #   数値ベクトルに変換する必要がある。
    #
    #   encode_window(w) は、
    #       window 内の各アミノ酸を 20次元 one-hot に変換し、
    #       それらを連結したベクトル（20 × window 次元）を返す。
    #
    #   例：window=3 の場合
    #       "ACX" → [one-hot(A), one-hot(C), one-hot(X)] を連結
    #
    #   これにより、MLP が扱える数値特徴量 X_pred が得られる。
    # ------------------------------------------------------------
    X_pred = np.array([encode_window(w) for w in windows])

    # ------------------------------------------------------------
    # 【3. MLP による生予測（0/1/2 の整数ラベル）】
    # ------------------------------------------------------------
    # 目的：
    #   学習済み MLP モデル clf を使って、
    #   各ウィンドウに対する二次構造（H/E/C）を予測する。
    #
    #   clf.predict(X_pred) の出力は整数ラベル：
    #       0 → H（Helix）
    #       1 → E（β-sheet）
    #       2 → C（Coil）
    #
    #   まだ文字列ではなく、数値のまま。
    # ------------------------------------------------------------
    pred = clf.predict(X_pred)

    # ------------------------------------------------------------
    # 【4. 数値ラベル（0/1/2）を文字（H/E/C）に変換】
    # -----------------------------------------------------
    # 目的：
    #   モデルの出力は整数ラベルなので、
    #   人間が読める二次構造文字列に戻す必要がある。
    #
    #   inv = {0:'H', 1:'E', 2:'C'} を使って逆変換し、
    #   予測結果を 1 本の文字列に連結する。
    #
    #   例：
    #       pred = [0,0,1,2,2]
    #       raw = "HHECC"
    #
    #   この raw は「スムージング前の生予測」。
    # --------------------------------------------------
    raw = ''.join(inv[p] for p in pred)

    # ------------------------------------------------------------
    # 【5. smoothing（平滑化）を適用して最終二次構造を返す】
    # ------------------------------------------------------------
    # 目的：
    #   MLP の生予測はノイズが多く、
    #       ・孤立した H/E
    #       ・途切れた βシート
    #       ・短すぎるヘリックス
    #   など、生物学的に不自然なパターンが出やすい。
    #
    #   smooth_ss(raw) は、
    #       ・H の前後2残基を H に寄せる
    #       ・E の前後2残基を E に寄せる（強化版）
    #   といったルールで連続性を補正し、
    #   より自然な二次構造列に仕上げる。
    #
    #   最終的に返されるのは、
    #       「スムージング済みの二次構造列」
    #   であり、これが predict_ss() の最終出力となる。
    # ----------------------------------------------------------
    return smooth_ss(raw)

