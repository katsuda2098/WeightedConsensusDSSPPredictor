# 6. smoothing（β-sheet 対応版）
#    H と E の連続性を強化して物理的に自然な構造にする
# ============================================

def smooth_ss(ss):
    # ------------------------------------------------------------
    # 二次構造æ."）をスムージング処理する関数
    # ------------------------------------------------------------
    # 【目的】
    #   DSSP などから得られた二次構造列 ss（文字列）に対して、
    #   周囲の残基情報を参照しながら「平滑化（smoothing）」を行う。
    #   その準備として、まず文字列をリスト化し、長さを取得する。
    #
    # 【ss = list(ss) の意味】
    #   ・Python の文字列は「イミュータブル（変更不可）」のため、
    #     ss[3] = 'H' のように直接書き換えることができない。
    #   ・スムージング処理では、特定位置の文字を置き換える必要があるため、
    #     文字列を「変更可能なリスト」に変換しておく。
    #
    #   例：
    #       ss = "HECCH"
    #       list(ss) → ['H', 'E', 'C', 'C', 'H']
    #
    #   これにより、ss[i] = 'E' のような更新が可能になる。
    #
    # 【n = len(ss) の意味】
    #   ・二次構造列の長さ（残基数）を取得する。
    #   ・後続のループ処理（i=0〜n-1）で、
    #     各位置の前後の残基を参照しながらスムージングするために必要。
    #
    #   例：
    #       ss = ['H','E','C','C','H']
    #       n = 5
    #
    #   これにより、境界チェック（i-1 >= 0、i+1 < n など）が簡単になる。
    # ------------------------------------------------------------
    ss = list(ss)
    n = len(ss)

    # ------------------------------------------------------------
    # 【H smoothing：ヘリックス領域を“連続的な形”に補正する処理】
    # ------------------------------------------------------------
    # ■ この処理が必要な理由
    #   MLP の生予測では、以下のような「不自然な H の途切れ」がよく発生する：
    #       例） ... C C H C C ...
    #   しかし実際のタンパク質では、αヘリックスは 3～4 残基以上の
    #   “連続した”構造として現れることがほとんどで、
    #   単発の H が点在することは生物学的にほぼ起こらない。
    #
    #   そこで、
    #       「H が 1 つでも出たら、その前後の残基も H に寄せて連続化する」
    #   というスムージングを行い、より自然な二次構造列に補正する。
    #
    # ------------------------------------------------------------
    # ■ 何をしているのか（処理の流れ）
    #   1. ss を左から右へ 0〜n-1 の順に走査する
    #   2. ss[i] が 'H' だった場合、
    #   3. その位置 i を中心に「前後 2 残基」の範囲を H に書き換える
    #
    #   つまり、i を中心に以下の範囲を H にする：
    #       i-2, i-1, i, i+1, i+2
    #
    #   例）
    #       元の予測：  C C H C C
    #       i=2 が H の場合、
    #       j = 0〜4 のうち、範囲内の 0〜4 をすべて H にする
    #       → C C H C C  →  H H H H H
    #
    # ------------------------------------------------------------
    # ■ max() と min() を使う理由（境界処理）
    #   i が 0 や 1 のように配列の端に近い場合、
    #       i-2 や i+2 が範囲外（負の値や n 以上）になる。
    #
    #   そこで、
    #       max(0, i-2)   → 下限を 0 に固定（負のインデックスを防ぐ）
    #       min(n, i+3)   → 上限を n に固定（n 以上のアクセスを防ぐ）
    #
    #   これにより、どの位置 i でも安全に前後 2 残基を処理できる。 
    #
    # ------------------------------------------------------------
    # ■ なぜ「前後 2 残基」なのか（採用版の経験則）
    #   ・前後 1 だと補正が弱く、H が途切れやすい
    #   ・前後 3 以上だと補正が強すぎて、H が広がりすぎる
    #
    #   過去の採用版では「前後 2」が最も安定しており、
    #   ・孤立 H の除去
    #   ・自然なヘリックス長の再現
    #   ・過剰な H の拡大を防ぐ
    #   のバ最も良かったため、この設定を採用している。
    #
    # ------------------------------------------------------------
    # ■ この処理の効果（Before → After）
    #   ・孤立した H を自然なヘリックスに変換
    #       C C H C C  →  H H H H H
    #
    #   ・ヘリックスの端が欠ける問題を修正
    #       C H H H C  →  H H H H H
    #
    #   ・全体として、より生物学的に妥当な二次構造列になる
    # --------------------------------------------------
    for i in range(n):
        if ss[i] == 'H':
            # i を中心に前後 2 残基を H に書き換える
            for j in range(max(0, i-2), min(n, i+3)):
                ss[j] = 'H'

    # ------------------------------------------------------------
    # 【E smoothing：βシート領域を“連続的な形”に補正する処理（強化版）】
    # ------------------------------------------------------------
    # ■ この処理が必要な理由
    #   MLP の生予測では、βシート（E）が以下のように途切れたり、
    #   単発で出たりする「ノイズ」が頻繁に発生する：
    #
    #       例） ... C C E C C ...
    #
    #   しかし実際のタンパク質では、βシートは
    #       ・最低でも 2〜3 残基以上の連続したストランド
    #       ・H よりも短いが、C よりも連続性が高い
    #   という特徴を持つため、単発の E は生物学的に不自然。
    #
    #   そこで、
    #       「E が出たら、その前後の残基も E に寄せて連続化する」
    #   というスムージングを行い、βシートらしい形に補正する。
    #
    # ------------------------------------------------------------
    # ■ 今回は “強化版” の E smoothing（前後2残基）
    #   ・採用版では E smoothing は前後1 だったが、
    #     βシートの予測が弱い問題を改善するため、
    #     H と同じ「前後2残基」に拡大している。
    #
    #   これにより、
    #       ・E の孤立点を確実に除去
    #       ・短すぎる E を自然な長さに補正
    #       ・E の予測が出にくい問題を改善
    #   といった効果が期待できる。
    #
    # ------------------------------------------------------------
    # ■ 何をしているのか（処理の流れ）
    #   1. ss を左から右へ 0〜n-1 の順に走査する
    #   2. ss[i] が 'E' だった場合、
    #   3. その位置 i を中心に「前後 2 残基」の範囲を E に書き換える
    #
    #   つまり、i を中心に以下の範囲を E にする：
    #       i-2, i-1, i, i+1, i+2
    #
    #   例）
    #       元の予測：  C C E C C
    #       i=2 が E の場合、
    #       j = 0〜4 のうち、範囲内の 0〜4 をすべて E にする
    #       → C C E C C  →  E E E E E
    #
    # ------------------------------------------------------------
    # ■ max() と min() を使う理由（境界処理）
    #   i が 0 や 1 のように配列の端に近い場合、
    #       i-2 や i+2 が範囲外（負の値や n 以上）になる。
    #
    #   そこで、
    #       max(0, i-2)   → 下限を 0 に固定（負のインデックスを防ぐ）
    #       min(n, i+3)   → 上限を n に固定（n 以上のアクセスを防ぐ）
    #
    #   ※ i+3 は「i+2 の 1つ先」  
    #     range() の右端は含まれないため、i+2 を含めるには i+3 が必要。
    #
    # ----------------------------------------------------
    # ■ なぜ「前後 2 残基」なのか（強化の理由）
    #   ・βシートは H より短いが、C よりは連続性が高い
    #   ・前後1 だと E が途切れやすく、予測が弱いまま
    #   ・前後2 にすると、E の連続性が安定し、孤立 E を確実に除去できる
    #
    #   特に今回のモデルでは E の予測が弱いため、
    #   smoothing を強化することで E の存在を“後押し”している。
    #
    # -----------------------------------------------------------
    # ■ この処理の効果（Before → After）
    #   ・孤立した E を自然な βシートに変換
    #       C C E C C  →  E E E E E
    #
    #   ・短すぎる E を補正して、βストランドらしい長さにする
    #
    #   ・E の予測が弱いモデルでも、E が出やすくなる
    #
    #   ・全体として、βシート領域が滑らかで連続的になる
    # ---------------------------------------------
    for i in range(n):
        if ss[i] == 'E':
            for j in range(max(0, i-2), min(n, i+3)):
                ss[j] = 'E'

    # ------------------------------------------------------------
    # 【スムージング後の二次構造リストを「文字列」に戻して返す】
    # ------------------------------------------------------------
    # ■ この関数 smooth_ss() の入力と出力
    #   入力：ss（例："HHECCH"） → 文字列
    #   処理中：['H','H','E','C','C'可能）
    #   出力："HHECCH" → 文字列（変更後）
    #
    #   ※関数の外では「文字列」として扱いたいため、
    #     最後にリストを文字列へ戻す必要がある。
    #
    # ------------------------------------------------------------
    # ■ なぜ join() を使うのか？
    #   ・Python の文字列は「イミュータブル（変更不可）」なので、
    #     スムージング処理中はリストとして扱っていた。
    #   ・しかし、最終的に返すべき形式は
    #         "HHHEEECCCHH"
    #     のような **1本の文字列**。
    #
    #   join() は、リストの要素を「区切り文字なし」で連結して
    #   1つの文字列にまとめるための関数。
    #
    #   例：
    #       ss = ['H','E','C']
    #       ''.join(ss) → "HEC"
    #
    # ------------------------------------------------------------
    # ■ ''（空文字）を使う理由
    #   ・区切り文字を入れずに連結したいから。
    #   ・もし '-' を使うと "H-E-C" のようになってしまう。
    #
    #   今回は二次構造列なので、区切りは不要 → '' を使用。
    #
    # ------------------------------------------------------------
    # ■ この return の意味
    #   ・スムージング処理で補正された二次構造列を
    #     「文字列として」呼び出し元に返す。
    #
    #   ・呼び出し側では、
    #         smoothed = smooth_ss(predicted_ss)
    #     のようにして、補正済みの二次構造列を受け取れる。
    #
    # ------------------------------------------------------------
    return ''.join(ss)

