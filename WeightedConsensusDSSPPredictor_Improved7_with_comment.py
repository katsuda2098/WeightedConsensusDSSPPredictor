# 8. input.txt を自動で読み込む関数
# ============================================
def predict_from_input_file(path="input.txt", window=15):
    """
    指定されたテキストファイルからアミノ酸配列を読み込み、
    その配列に対して二次構造予測を実行する関数。

    【目的】
    - ユーザーが input.txt に書いたアミノ酸配列を読み取り、
      そのままモデルに渡して予測を行う。  
    - コマンドライン引数や GUI を使わず、
      「input.txt を書き換えるだけ」で予測できる簡易インターフェースを提供する。

    【入力ファイルの仕様】
    - プレーンテキスト形式（例：input.txt）
    - 1 行目にアミノ酸一次配列のみを記述する
        例:
            SSSAAGSLGG
    - FASTA 形式（">" で始まるヘッダ行）は非対応
    - 複数行にまたがる配列は想定しない（1 行のみ）
    - 前後の空白や改行は自動で除去される
    - 大文字・小文字は混在していてもよい（内部で大文字に統一）

    【処理内容】
    1. 指定されたパスのファイルを読み込みモードで開く
    2. ファイル全体を読み込み、前後の空白・改行を strip() で除去
    3. アミノ酸表記の揺れを防ぐため、すべて大文字に変換
    4. 読み込んだ配列を後続の予測処理に渡す

    【設計上の意図】
    - 「input.txt き換えるだけで予測できる」ことを最優先にした設計。
    - 入力バリデーション（不正文字チェック、複数行対応など）は行わず、
      入力形式の保証はユーザー側の責務とする。
    - 入力処理を関数として独立させることで、
        * テストの容易性
        * 入力形式変更への柔軟性
        * スクリプト全体の可読性向上
      を実現している。

    【引数】
    path : str
        読み込むアミノ酸配列ファイルのパス（デフォルト: "input.txt"）
    window : int
        モデルが使用するスライディングウィンドウ幅（デフォルト: 15）

    【返り値】
    特になし（予測結果は関数内で表示または別処理に渡される）
    """

    # ------------------------------------------------------------
    # 入力ファイル（例: input.txt）を開き、
    # アミノ酸配列を読み込む。
    #
    # read() を使う理由：
    #   - 1 行のが、万一複数行があっても
    #     まとめて読み込んで strip() で前後の空白を除去できるため。
    #
    # strip() の役割：
    #   - 改行文字（\n）や前後の空白を取り除き、
    #     モデルに渡す配列をクリーンな状態にする。
    #
    # upper() の役割：
    #   - アミノ酸表記の大文字・小文字の揺れを吸収し、
    #     モデル内部の辞書（A, C, D, ...）と整合性を取る。
    # --------------------------------------------------------
    with open(path, "r") as f:
        seq = f.read().strip().upper()

    # ------------------------------------------------------------
    # 読み込んだアミノ酸配列をログとして表示する。
    #
    # 【目的】
    # - ユーザーが input.txt に書いた内容が正しく読み込まれたかを
    #   目視で確認できるようにするため。
    # - デバッグ時に「入力が間違っていたのか」「予測処理が間違っているのか」 
    #   を切り分けるための重要なチェックポイント。
    #
    # 【INFO 表示の意図】
    # - 研究コードでは print() を使うことが多いため、
    #   ログレベルを簡易的に示すために "[INFO]" を付けている。
    # - 実行ログを追いやすくし、後から結果を再現しやすくする。
    # ------------------------------------------------------------
    print("[INFO] Loaded sequence from input.txt:", seq)

    # ----------------------------------------------
    # 読み込んだアミノ酸配列 seq に対して、
    # 二次構造予測モデル（predict_ss）を実行する。
    #
    # 【predict_ss の役割】
    # - スライディングウィンドウ法で配列を分割
    # - one-hot エンコードで数値化
    # - 学習済み MLPClassifier による生予測
    # - ラベル（H/E/C）への変換
    # - スムージング処理によるノイズ除去
    #
    # 【window 引数の意味】
    # - モデルが参照するアミノ酸の範囲（例：15 なら前後7残基）
    # - 予測精度に影響するため、関数外から変更可能にしている
    #
    # 【設計意図】
    # - 入力処理（ファイル読み込み）と予測処理（predict_ss）を分離し、
    #   責務を明確化することでコードの保守性を高めている。
    # ------------------------------------------------------------
    ss = predict_ss(seq, window=window)

    # ----------------------------------------------
    # 予測された二次構造（ss）をログとして表示する。
    #
    # 【目的】
    # - モデルがどのような二次構造を返したかを確認するため。
    # - 入力配列と予測結果を並べて確認することで、
    #   モデルの挙動をデバッグしやすくする。
    #
    # 【表示形式】
    # - 例: "HHHCCEECCHH"
    # - 1 文字 1 残基の形式で、配列長と一致する。
    #
    # 【INFO 表示の意図】
    # - 実行ログを整理し、後から再現性を確保するため。
    # ------------------------------------------------------------
    print("[INFO] Predicted SS:", ss)

    # ------------------------------------------------------------
    # 予測結果（ss）を呼び出し元に返す。
    #
    # 【返り値の役割】
    # - スクリプト内の他の処理（保存、可視化、比較など）に渡すため。
    # - 関数をテストしやすくするため、print だけでなく return も行う。
    #
    # 【設計意図】
    # - 「予測処理」と「結果の利用」を分離し、
    #   再利用性の高い関数として設計している。
    # ------------------------------------------------------------
    return ss

