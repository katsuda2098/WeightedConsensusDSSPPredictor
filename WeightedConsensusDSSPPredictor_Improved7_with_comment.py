# ------------------------------------------------------------
# クラス重みの手動調整（モデルの予測バランスを制御する重要ステップ）
# ------------------------------------------------------------
# 【目的】
#   compute_class_weight("balanced") によって自動計算された重みは、
#   データの出現頻度に基づく「基本的な補正」にすぎない。
#
#   しかし今回の目的は、
#       ・β-sheet（E）をもっと強く予測させたい
#       ・helix（H）は強すぎるので少し弱めたい
#       ・coil（C）はそのままでよい
#   という “モデルの性格づけ” を行うこと。
#
#   そのため、クラスごとの重みを手動で倍率調整して、
#   学習時の影響力を意図的に変える。
#
# 【処理内容】
#   cw[0] → H（helix）の重み
#   cw[1] → E（β-sheet）の重み
#   cw[2] → C（coil）の重み
#   ・H（cw[0]）は 2.0 倍：  
#       → 以前の「採用版」より弱めたいので、控えめな補強に留める。
#
#   ・E（cw[1]）は 4.0 倍：  
#       → β-sheet を強化したいので、H よりも大きく増やす。
#         これにより、E の誤分類を強くペナルティ化し、
#         モデルが E を積極的に学習するようになる。
#
#   ・C（cw[2]）は変更なし：  
#       → coil は過剰に予測されやすい傾向があるため、
#         追加の強化は不要。
#
# 【効果】
#   ・E（β-sheet）の予測が出やすくなる（強化）
#   ・H（helix）は出すぎないように抑制される（弱化）
#   ・C（coil）は現状維持
#
#   これにより、モデル全体の予測バランスを
#   「E を重視した挙動」に調整できる。
# ------------------------------------------------------------

#cw[0] *= 2.0   # H（helix）：採用版より弱めの補強
#cw[1] *= 4.0   # E（β-sheet）：強化して予測を出やすくする
# C（coil）はそのまま
if 0 in cw:
    cw[0] *= 2.0
if 1 in cw:
    cw[1] *= 4.0
if 2 in cw:
    cw[2] *= 1.0


# ------------------------------------------------------------
# 調整後のクラス重みをログ出力して確認する
# ------------------------------------------------------------
# 【目的】
#   ・H/E/C の重みを手動で調整した後、
#     最終的にどのような値になっているかを確認するためのログ。
#   ・学習結果が期待通りにならない場合、
#     まずここで重みが正しく設定されているかをチェックできる。
#
# 【例】
#   adjusted class_weight = {0: 14.3, 1: 85.6, 2: 0.37}
#   → H=14.3, E=85.6, C=0.37 のように、E が最も強く補正されていることが分かる。
# ------------------------------------------------------------
print("[INFO] adjusted class_weight =", cw)

# ------------------------------------------------------------
# 各サンプルに対応する「サンプル重みベクトル」を作成する
# ----------------------------------------------------
# 【目的】
#   MLPClassifier は class_weight を直接受け取れないため、
#   各サンプルごとに重みを割り当てた sample_weight を fit() に渡す必要がある。
#
# 【処理内容】
#   y は学習データのクラスラベル配列（例： [0,2,2,1,0, ...] ）。
#   各ラベル y[i] に対して、cw[y[i]] を参照し、
#   「そのサンプルが属するクラスの重み」を取り出す。
#
#   例：
#       y = [0, 2, 2, 1]
#       cw = {0: 14.3 2: 0.37}
#
#       sample_weight =
#           [cw[0], cw[2], cw[2], cw[1]]
#         = [14.3, 0.37, 0.37, 85.6]
#
# 【効果】
#   ・E（β-sheet）の重みを大きくした場合、
#     E のサンプルは学習時に「より重要」とみなされる。
#   ・C の重みが小さい場合、
#     C のサンプルは「軽く扱われる」ため、過剰予測を抑制できる。
#   ・これにより、モデルの予測バランスを意図的に調整できる。
# -------------------------------------------------
sample_weight = np.array([cw[label] for label in y])

# ------------------------------------------------------------
# MLP（多層パーセプトロン）モデルの構築
# ------------------------------------------------------------
# 【目的】
#   DSSP 由来の特徴量（ウィンドウ特徴量）から
#   H/E/C の二次構造を分類するためのニューラルネットワークを構築する。
#
# 【hidden_layer_sizes=(512,256,128) の意味】
#   ・3 層めの MLP を構築している。
#   ・各層のユニット数は 512 → 256 → 128 と段階的に減らしており、
#     高次特徴 → 中間特徴 → 低次特徴 へと圧縮しながら学習する構造。
#   ・ウィンドウ法では入力次元が比較的大きくなるため、
#     3 層構造は局所パターン（ヘリックス/シートの特徴）を捉えやすい。
#
# 【activation='relu' の意味】
#   ・ReLU（Rectified Linear Unit）を使用。
#   ・勾配消トワークでも安定して学習できる。
#
# 【max_iter=500 の意味】
#   ・最大 500 エポックまで学習を繰り返す。
#   ・ウィンドウ特徴量＋クラス重み補正では収束に時間がかかるため、
#     デフォルト（200）より多めに設定している。
# ------------------------------------------------------------
clf = MLPClassifier(
    hidden_layer_sizes=(512,256,128),  # 深めの3層 MLP（特徴圧縮しながら学習）
    activation='relu',
    max_iter=500
)

# ------------------------------------------------------------
# MLP の学習処理
# ------------------------------------------------------------
# 【目的】
#   ・X（特徴量）と y（正解ラベル）を使って MLP を学習させる。
#   ・sample_weight を渡すことで、クラスの偏りを補正しながら学習できる。
#
# 【sample_weight の役割】
#   ・各サンプルに「重み」を与えることで、
#       - E（β-sheet）を強く学習させãlix）は適度に強調
#       - C（coil）は過剰に学習させない
#     といった “予測バランスの調整” が可能になる。
#
# 【fit() の内部で起きていること】
#   ・誤差（loss）を計算する際、sample_weight が掛け算される。
#   ・重みが大きいクラスの誤差は「より重要」とみなされ、
#     勾配更新で優先的に改善される。
#   ・これにより、データの偏りを補正しつつ、
#     特定クラス（E習が行われる。
# ------------------------------------------------------------
print("[INFO] Training MLP...")
clf.fit(X, y, sample_weight=sample_weight)
print("[INFO] Training complete.")

